/** Accent- and case-insensitive matching used by every suggestion list. */
export function normalizeSuggestion(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
}

/**
 * Filters suggestions by the typed text. An empty query keeps the first
 * entries so the options are discoverable as soon as the field receives focus.
 */
export function filterSuggestions(
  options: readonly string[],
  query: string,
  limit = 8,
): string[] {
  const normalizedQuery = normalizeSuggestion(query)

  if (!normalizedQuery) return options.slice(0, limit)

  return options
    .filter((option) =>
      normalizeSuggestion(option).includes(normalizedQuery),
    )
    .slice(0, limit)
}

/**
 * Language entries are stored in the existing `tags` array. Combining the
 * language, an optional proficiency label and an optional CEFR level keeps the
 * document contract unchanged while remaining readable in the A4 preview.
 */
export function formatLanguageTag(
  language: string,
  level: string,
  cefr: string,
): string {
  const name = language.trim()
  if (!name) return ''

  const qualifierParts: string[] = []
  if (level.trim()) qualifierParts.push(level.trim())
  if (cefr.trim()) {
    qualifierParts.push(level.trim() ? `(${cefr.trim()})` : cefr.trim())
  }

  const qualifier = qualifierParts.join(' ')

  return (qualifier ? `${name} — ${qualifier}` : name).slice(0, 60)
}
